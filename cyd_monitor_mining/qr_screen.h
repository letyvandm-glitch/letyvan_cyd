// Dessine un QR code bitmap (PROGMEM) sur le TFT
static void drawQRBitmap(const uint8_t* data, uint8_t size, uint8_t bpr,
                          int16_t cx, int16_t cy, uint8_t scale) {
  extern TFT_eSPI tft;
  int16_t totalW = (int16_t)size * scale;
  int16_t x0 = cx - totalW / 2;
  int16_t y0 = cy - totalW / 2;
  tft.fillRect(x0 - scale, y0 - scale, totalW + scale*2, totalW + scale*2, TFT_WHITE);
  for (uint8_t row = 0; row < size; row++) {
    for (uint8_t col = 0; col < size; col++) {
      uint8_t byte_idx = col / 8;
      uint8_t bit_pos  = 7 - (col % 8);
      uint8_t b = pgm_read_byte(&data[row * bpr + byte_idx]);
      bool dark = (b >> bit_pos) & 1;
      uint16_t color = dark ? TFT_BLACK : TFT_WHITE;
      tft.fillRect(x0 + (int16_t)col*scale, y0 + (int16_t)row*scale, scale, scale, color);
    }
  }
}
